// st_pre.sv -- pass 0 (pre): ISP slot RGB565 -> p0, the network input.
//
// Input: the crop of the ISP frame, straight from tile_dma_rd.  The DMA reads
// base = slot + 160*2 bytes, 120 beats per line (960 px, 8 px per beat), 720
// lines, so beat xb of line y carries source pixels 8*xb .. 8*xb+7 of the
// crop, pixel 0 in bits [15:0].
// Output: 128-bit beats of the p0 DDR format (C = 3, elem 1, PB = 16), one
// beat per output pixel: bytes 0..2 = the quantised R, G, B codes, the rest
// zero, sof on the first beat of the frame and eol on the last beat of every
// output line (320 beats).  It feeds tile_dma_wr directly.
//
// Per output pixel and channel the datapath is exactly st_golden.pre():
//
//   rgb = vid_pkg::unpack565(px)                     bit replication
//   sum = 3x3 box sum of the RGB8 codes over the block
//         x 3*ox .. 3*ox+2, y 3*oy .. 3*oy+2
//   avg = (sum * 455 + 2075) >> 12                   == round(sum / 9), 8 bit
//   q   = LUT[avg]                                   st_pre_lut.hex, 0..127
//
// The LUT is the 256-entry point-0 quantiser of tools/st_golden.py
// (Net.quantize_input), generated by tools/st_gen_prelut.py.  LUT_FILE is a
// $readmemh path relative to where the simulation runs.
//
// Structure.  A column accumulator row of 320 entries of 3 x 12 bits
// (3*3*255 = 2295 needs 12) holds the running box sum over the 3 source lines
// of the band being built.  Three source lines complete a band; its row is
// then averaged, looked up and emitted, and the next band overwrites the row
// entry by entry -- the first line of a band writes instead of adding, so
// there is no clear pass.
//
// Column mapping.  A beat owns the eight 3-pixel windows that start at source
// pixels 8*xb-2 .. 8*xb+5: its own pixels plus the last two of the previous
// beat, carried in registers.  Of those eight windows exactly 2 or 3 start on
// a multiple of 3, i.e. are output columns, and the pattern repeats with
// xb mod 3:
//
//   xb mod 3 = 0 -> windows 2, 5          (2 columns)
//   xb mod 3 = 1 -> windows 0, 3, 6       (3 columns)
//   xb mod 3 = 2 -> windows 1, 4, 7       (3 columns)
//
// Eight columns per 3 beats, 320 per line: a counter modulo 3 and a column
// counter replace any division.
//
// Rate: read-modify-write runs one column per cycle, 3 cycles for a 2-column
// beat and 4 for a 3-column one (33 cycles per 3 beats), then 320 cycles to
// emit the row: 3.7 cycles per source beat, about 400k cycles per frame.  The
// input is accepted only while no beat is in flight; the DMA's FIFO absorbs
// that, and the DMA is the bottleneck either way.
//
// Resources: the column accumulator at 320 x 36 bits is 2 RAM10; the LUT at
// 3 x 256 x 8 bits is 3 RAM10 (one copy per channel, all three lookups in one
// cycle); the three `* 455` are 12 x 9-bit constant multiplies (3 DSP slices,
// or LUT logic).  Nothing else is stored.
module st_pre
    import vid_pkg::*;
#(
    parameter int SRC_W = 960,               // crop width, pixels
    parameter int SRC_H = 720,               // crop height, lines
    parameter string LUT_FILE = "./rtl/st_accel_new/gen/tiny_dw/st_pre_lut.hex"
) (
    input  logic         clk,
    input  logic         rst_n,

    // Source: the ISP crop as AXI beats, sof/eol per line.
    input  logic         in_valid,
    output logic         in_ready,
    input  logic [127:0] in_data,
    input  logic         in_sof,
    input  logic         in_eol,

    // Results: p0 DDR beats.
    output logic         out_valid,
    input  logic         out_ready,
    output logic [127:0] out_data,
    output logic         out_sof,
    output logic         out_eol,

    input  logic         start,              // one cycle, while idle
    output logic         busy,               // until the last beat is accepted
    output logic         err                // input framing mismatch, sticky
);
    // ------------------------------------------------------------- geometry
    localparam int BPL   = SRC_W / BEAT_PIX;    // source beats per line
    localparam int OUT_W = SRC_W / 3;           // output pixels per line
    localparam int OUT_H = SRC_H / 3;
    localparam int NW    = BEAT_PIX + 2;        // 2 carried pixels + the beat
    localparam int CW    = 12;                  // per-channel box sum
    localparam int ACCW  = 3 * CW;
    localparam int XW    = $clog2(BPL);        // 0 only for a one-beat line
    localparam int COLW  = (OUT_W > 1) ? $clog2(OUT_W) : 1;   // 9: 0..319
    localparam int YW    = (OUT_H > 1) ? $clog2(OUT_H) : 1;   // 8: 0..239
    localparam int EW    = COLW + 1;            // emission column, 0..OUT_W

    initial begin
        if (SRC_W % BEAT_PIX != 0)
            $error("st_pre: SRC_W must be a multiple of %0d", BEAT_PIX);
        if (SRC_W % 3 != 0 || SRC_H % 3 != 0)
            $error("st_pre: the geometry must be a multiple of 3");
        if (BPL % 3 != 0)
            $error("st_pre: a source line must be a whole number of 3-beat groups");
        if (SRC_W % 24 != 0)
            $error("st_pre: SRC_W must be a multiple of 24");
    end

    // ------------------------------------------------------------ LUT (ROM)
    // One copy per channel so all three lookups happen in the same cycle.
    logic [7:0] lut_r [256], lut_g [256], lut_b [256];
    initial begin
        $readmemh(LUT_FILE, lut_r);
        $readmemh(LUT_FILE, lut_g);
        $readmemh(LUT_FILE, lut_b);
    end

    // ------------------------------------------------------------- control
    typedef enum logic  { ST_IDLE, ST_RUN } state_e;
    // PH_W0/PH_W1/PH_W2 are 0/1/2 so the read address is c0_q + ph.
    typedef enum logic [1:0] { PH_ACC = 2'd3, PH_W0 = 2'd0, PH_W1 = 2'd1, PH_W2 = 2'd2 } ph_e;
    state_e state;
    ph_e    ph;

    logic            running;
    logic            emit;        // ST_RUN: the row of the band is being emitted
    logic [XW-1:0]   xb;          // source beat within the line
    logic [1:0]      xb3;         // xb mod 3
    logic [1:0]      sy;          // source line within the band, 0..2
    logic [YW-1:0]   orow;        // output row, 0..OUT_H-1
    logic [COLW-1:0] ccol;        // next output column to accumulate

    // The beat in flight.
    logic [127:0]    data_q;
    rgb888_t         pc0, pc1;    // last two pixels of the previous beat
    logic            first_q;     // first line of the band: write, don't add
    logic [1:0]      ncol_q;      // columns this beat owns, 2 or 3
    logic [2:0]      k0_q, k1_q, k2_q;
    logic [COLW-1:0] c0_q;
    logic            lastbeat_q;

    assign busy = running;

    // ---------------------------------------------------- column accumulator
    // One read port and one write port, never the same address in a cycle:
    // the write of a column trails its read by one cycle (PH_n reads column n,
    // PH_n+1 writes it), so the RAM needs no read-during-write mode.
    logic [ACCW-1:0] acc_mem [OUT_W];
    logic [COLW-1:0] acc_raddr_d;               // combinational read address
    logic [ACCW-1:0] acc_q;                     // data for acc_raddr_d, 1 cycle on
    logic            wr_en;
    logic [COLW-1:0] wr_addr;
    logic [ACCW-1:0] wr_data;

    // The read is held while the output beat is stalled: the emission stages
    // then freeze together, so one stalled cycle cannot consume a column that
    // the pipeline has not emitted yet.  A write only happens on the input
    // side, which never runs while the emitter is stalled.
    always_ff @(posedge clk) begin
        if (!stall) acc_q <= acc_mem[acc_raddr_d];
        if (wr_en)  acc_mem[wr_addr] <= wr_data;
    end

    // --------------------------------------------------- input window sums
    rgb888_t    wpx [NW];
    logic [9:0] win_r [BEAT_PIX], win_g [BEAT_PIX], win_b [BEAT_PIX];

    always_comb begin
        wpx[0] = pc0;
        wpx[1] = pc1;
        for (int p = 0; p < BEAT_PIX; p++)
            wpx[p+2] = unpack565(rgb565_t'(data_q[16*p +: 16]));
        for (int k = 0; k < BEAT_PIX; k++) begin
            win_r[k] = 10'(wpx[k].r) + 10'(wpx[k+1].r) + 10'(wpx[k+2].r);
            win_g[k] = 10'(wpx[k].g) + 10'(wpx[k+1].g) + 10'(wpx[k+2].g);
            win_b[k] = 10'(wpx[k].b) + 10'(wpx[k+1].b) + 10'(wpx[k+2].b);
        end
    end

    // Window k as an accumulator increment: {r, g, b} channel fields.
    function automatic logic [ACCW-1:0] col_add(input logic [2:0] k);
        logic [ACCW-1:0] d;
        d = '0;
        d[CW-1:0]      = CW'(win_b[k]);
        d[2*CW-1:CW]   = CW'(win_g[k]);
        d[ACCW-1:2*CW] = CW'(win_r[k]);
        col_add = d;
    endfunction

    // ------------------------------------------- per-beat column plan
    wire [1:0] ncol_now;
    wire [2:0] k0_now, k1_now, k2_now;
    assign {ncol_now, k0_now, k1_now, k2_now} =
        (xb3 == 2'd0) ? {2'd2, 3'd2, 3'd5, 3'd0} :
        (xb3 == 2'd1) ? {2'd3, 3'd0, 3'd3, 3'd6} :
                        {2'd3, 3'd1, 3'd4, 3'd7};

    // ------------------------------------------------------------- output
    logic         ovalid;
    logic [127:0] odata;
    logic         osof, oeol;
    assign out_valid = ovalid;
    assign out_data  = odata;
    assign out_sof   = osof;
    assign out_eol   = oeol;

    wire stall = ovalid && !out_ready;

    // Emission pipeline, three stages after the address: A carries the tags
    // while acc_q holds the column's sum, B averages and looks it up, C packs
    // the beat.  (acc_q itself is the RAM's output register, one cycle behind
    // the address it was given.)
    logic [EW-1:0] e_col;         // next column to issue, 0..OUT_W
    logic          s1_v, s1_sof, s1_eol;
    logic          s2_v, s2_sof, s2_eol;
    logic [7:0]    s2_qr, s2_qg, s2_qb;

    wire pv0 = emit && (e_col < EW'(OUT_W));

    // round(sum / 9) for sum <= 2295: (sum * 455 + 2075) >> 12.
    function automatic logic [7:0] avg8(input logic [CW-1:0] s);
        logic [20:0] p;
        p    = 21'(s) * 21'd455 + 21'd2075;
        avg8 = 8'(p >> 12);
    endfunction

    // ------------------------------------------------------------ FSM
    // Accept phase: a new beat enters; the read address is already its first
    // column.  PH_W0..PH_W2 then write the columns of the beat, one per cycle,
    // each one cycle after it was read.
    assign in_ready = (state == ST_RUN) && !emit && (ph == PH_ACC);

    // The RAM's read data is one cycle behind its address, so a column is
    // written in the cycle after the address that read it: PH_W0 writes the
    // first column and addresses the second, PH_W1 the second and the third.
    // The address of a two-column beat's third slot is never consumed (the
    // beat's phase ends first); OUT_W-1 keeps it inside the RAM.
    always_comb begin
        acc_raddr_d = COLW'(e_col);
        if (!emit) begin
            if (ph == PH_ACC)   acc_raddr_d = ccol;
            else if (ph == PH_W0) acc_raddr_d = c0_q + COLW'(1);
            else                  acc_raddr_d = (c0_q + COLW'(2) < COLW'(OUT_W))
                                              ? c0_q + COLW'(2) : COLW'(OUT_W - 1);
        end
    end

    wire exp_sof = (sy == 2'd0) && (orow == '0) && (xb == '0);
    wire exp_eol = (xb == XW'(BPL - 1));
    // This cycle completes the beat: its last column is written.
    wire beat_end = (state == ST_RUN) && !emit &&
                    ((ph == PH_W1 && ncol_q == 2'd2) || ph == PH_W2);

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state   <= ST_IDLE;
            ph      <= PH_ACC;
            running <= 1'b0;
            emit    <= 1'b0;
            err     <= 1'b0;
            wr_en   <= 1'b0;
            ovalid  <= 1'b0;
            s1_v    <= 1'b0;
            s2_v    <= 1'b0;
            s1_sof  <= 1'b0;
            s1_eol  <= 1'b0;
            s2_sof  <= 1'b0;
            s2_eol  <= 1'b0;
            s2_qr   <= '0;
            s2_qg   <= '0;
            s2_qb   <= '0;
            e_col   <= '0;
            xb      <= '0;
            xb3     <= '0;
            sy      <= '0;
            orow    <= '0;
            ccol    <= '0;
            data_q  <= '0;
            pc0     <= '0;
            pc1     <= '0;
            first_q <= 1'b0;
            ncol_q  <= 2'd0;
            k0_q    <= 3'd0;
            k1_q    <= 3'd0;
            k2_q    <= 3'd0;
            c0_q    <= '0;
            lastbeat_q <= 1'b0;
            wr_addr <= '0;
            wr_data <= '0;
            odata   <= '0;
            osof    <= 1'b0;
            oeol    <= 1'b0;
        end else begin
            wr_en <= 1'b0;

            if (start && state == ST_IDLE) begin
                running <= 1'b1;
                state   <= ST_RUN;
                ph      <= PH_ACC;
                emit    <= 1'b0;
                err     <= 1'b0;
                xb      <= '0;
                xb3     <= '0;
                sy      <= '0;
                orow    <= '0;
                ccol    <= '0;
                pc0     <= '0;
                pc1     <= '0;
            end

            // ------------------------------------------------ emission
            if (!stall) begin
                if (pv0) e_col <= e_col + EW'(1);
                s1_v   <= pv0;
                s1_sof <= pv0 && (orow == '0) && (e_col == '0);
                s1_eol <= pv0 && (e_col == EW'(OUT_W - 1));
                s2_v   <= s1_v;
                s2_sof <= s1_sof;
                s2_eol <= s1_eol;
                s2_qr  <= lut_r[avg8(acc_q[ACCW-1:2*CW])];
                s2_qg  <= lut_g[avg8(acc_q[2*CW-1:CW])];
                s2_qb  <= lut_b[avg8(acc_q[CW-1:0])];
                ovalid <= s2_v;
                odata  <= {104'd0, s2_qb, s2_qg, s2_qr};
                osof   <= s2_sof;
                oeol   <= s2_eol;
            end

            // The last output beat of a row hands the accumulator to the next
            // band, or ends the frame.
            if (ovalid && out_ready && oeol) begin
                emit <= 1'b0;
                if (orow == YW'(OUT_H - 1)) begin
                    running <= 1'b0;
                    state   <= ST_IDLE;
                end else begin
                    orow <= orow + YW'(1);
                end
            end

            // ----------------------------------------- one beat, 3-4 cycles
            if (state == ST_RUN && !emit) begin
                case (ph)
                    PH_ACC: begin
                        if (in_valid) begin
                            if (in_sof !== exp_sof || in_eol !== exp_eol) err <= 1'b1;
                            data_q     <= in_data;
                            first_q    <= (sy == 2'd0);
                            ncol_q     <= ncol_now;
                            k0_q       <= k0_now;
                            k1_q       <= k1_now;
                            k2_q       <= k2_now;
                            c0_q       <= ccol;
                            lastbeat_q <= (xb == XW'(BPL - 1));
                            ph         <= PH_W0;
                            if (xb == XW'(BPL - 1)) begin
                                xb   <= '0;
                                xb3  <= '0;
                                ccol <= '0;
                            end else begin
                                xb   <= xb + XW'(1);
                                xb3  <= (xb3 == 2'd2) ? 2'd0 : xb3 + 2'd1;
                                ccol <= ccol + COLW'(ncol_now);
                            end
                        end
                    end
                    PH_W0: begin
                        wr_en   <= 1'b1;
                        wr_addr <= c0_q;
                        wr_data <= first_q ? col_add(k0_q) : acc_q + col_add(k0_q);
                        ph      <= PH_W1;
                    end
                    PH_W1: begin
                        wr_en   <= 1'b1;
                        wr_addr <= c0_q + COLW'(1);
                        wr_data <= first_q ? col_add(k1_q) : acc_q + col_add(k1_q);
                        ph      <= (ncol_q == 2'd3) ? PH_W2 : PH_ACC;
                    end
                    default: begin
                        wr_en   <= 1'b1;
                        wr_addr <= c0_q + COLW'(2);
                        wr_data <= first_q ? col_add(k2_q) : acc_q + col_add(k2_q);
                        ph      <= PH_ACC;
                    end
                endcase
            end

            // End of a beat: carry its last two pixels into the next window
            // set, and advance the line or hand the row to the emitter.
            if (beat_end) begin
                pc1 <= unpack565(rgb565_t'(data_q[127:112]));
                pc0 <= unpack565(rgb565_t'(data_q[111: 96]));
                if (lastbeat_q) begin
                    if (sy == 2'd2) begin
                        emit  <= 1'b1;
                        sy    <= 2'd0;
                        e_col <= '0;
                    end else begin
                        sy <= sy + 2'd1;
                    end
                end
            end
        end
    end
endmodule
