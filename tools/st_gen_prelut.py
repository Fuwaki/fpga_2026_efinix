#!/usr/bin/env python3
"""Generate the point-0 quantiser table of pass 0 (pre) for st_pre.sv.

The table is the 256-entry LUT of tools/st_golden.py, Net.quantize_input:

    LUT[p] = clamp(round_half_away(f32(p) / 255 / f32(s0)), -qmax, qmax)

with s0 = point_scales[0] of the manifest.  st_pre applies it to the 2x2 box
average of the unpacked RGB8 codes, so the table is taken from the golden
model itself rather than recomputed here: the RTL and the reference cannot
disagree.  The default manifest is the guided net's
(/data/competition/2026fpga/st_work/p90_ln_w8a8); --manifest picks another.

Output (--out): one 8-bit value per line, two hex digits, addressed by the
average 0..255; the file is read with $readmemh.

Usage: st_gen_prelut.py [--manifest DIR] [--out FILE]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from st_golden import Net  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = Path("/data/competition/2026fpga/st_work/p90_ln_w8a8")
DEFAULT_OUT = ROOT / "rtl/st_accel_new/gen/guided/st_pre_lut.hex"


def lut_of(net: Net) -> np.ndarray:
    """The 256 codes point 0 takes, one per 8-bit average."""
    # A 256x1x3 image whose row p carries p in every channel: quantize_input
    # returns the same table on all three channels.
    img = np.zeros((256, 1, 3), np.uint8)
    img[:, :, 0] = np.arange(256, dtype=np.uint8)[:, None]
    img[:, :, 1] = img[:, :, 0]
    img[:, :, 2] = img[:, :, 0]
    q = net.quantize_input(img)                     # (3, 256, 1)
    assert q.shape == (3, 256, 1), q.shape
    assert np.array_equal(q[0], q[1]) and np.array_equal(q[1], q[2]), \
        "the point-0 LUT differs between the channels"
    lut = q[0, :, 0].astype(np.int64)
    assert lut.min() >= -net.qmax and lut.max() <= net.qmax, "LUT outside the clamp"
    assert (np.diff(lut) >= 0).all(), "the LUT is not monotone"
    return lut


def render(lut: np.ndarray, manifest: Path, mean: float) -> str:
    lines = [
        "// st_pre_lut.hex -- point 0 quantiser of pass 0 (pre), 256 x 8 bit.",
        f"// Generated by tools/st_gen_prelut.py from {manifest.name}; do not edit.",
        "// LUT[p] = clamp(round_half_away(f32(p) / 255 / f32(s0)), -qmax, qmax),",
        "// the tools/st_golden.py table Net.quantize_input builds.",
        f"// s0 = {mean!r}",
        f"// {len(lut)} entries, addressed by the 2x2 box average of the RGB8 code.",
    ]
    lines += [f"{int(v) & 0xFF:02X}" for v in lut]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args()

    mdir = Path(a.manifest)
    net = Net(str(mdir), False)
    lut = lut_of(net)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(lut, mdir, net.scales[0]))

    rel = out.relative_to(ROOT) if out.is_relative_to(ROOT) else out
    print(f"PASS st_gen_prelut: {rel}: {len(lut)} entries, "
          f"0..{lut.max()} (s0 = {net.scales[0]:.9f})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
