#!/usr/bin/env python3
"""Generate the LayerNorm coefficient ROM and the R LUT of st_norm.sv.

Writes into --out (all read with $readmemh):

  st_ln_b0.hex   the LN coefficients of one lane each, 256 x 48 bit words,
  ..             MSB first, one per line:
  st_ln_b3.hex     [44:18] B_c, 27-bit signed two's complement
                   [17:0]  G_c, 18-bit signed two's complement
                   [47:45] zero
                 Word a of lane b is channel 4a + b (a < 20); words 20..255
                 are zero -- st_norm keeps its FiLM coefficients at 128..147
                 of the same arrays, so the files must cover the whole array.
                 One file per lane is what lets st_norm's four lane arrays be
                 initialised by $readmemh straight into the RAM, the only
                 form Efinity infers RAM contents from.
  st_ln_lut.hex  LN_LUT, one 17-bit value per line (5 hex digits), addressed
                 by m - 256 with m the normalised D in [256, 1024).

Both tables are tools/st_guided.py's own: ln_consts (E, G_c, B_c) and
LN_LUT.  The generator checks that the model's E equals LN_E = 1 of the RTL
and fails loudly otherwise -- a different E would change every statistic.
It also checks the field widths the RTL assumes: |G_c| < 2^17 and
|B_c| < 2^26 for the coefficient word, and R < 2^17 for the LUT.

Usage: st_gen_norm.py --manifest DIR --out DIR
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import st_guided as G  # noqa: E402

LN_E_RTL = 1                # st_norm.sv: D = N*Q - S^2 + LN_E
MAX_CH = 80                 # channels the coefficient store holds
LANES = 4                   # coefficient arrays: one per group-stream lane
WORDS = 256                 # words per lane array (st_norm's coef_b*)
MUL_MAX = (1 << 17) - 1     # |G_c| < 2^17, 18-bit signed
OFF_MAX = (1 << 26) - 1     # |B_c| < 2^26, 27-bit signed
LUT_MAX = (1 << 17) - 1


def coeff_word(g: int, b: int) -> int:
    """{B_c[26:0], G_c[17:0]} as the 48-bit word st_norm reads."""
    return ((b & ((1 << 27) - 1)) << 18) | (g & ((1 << 18) - 1))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args()

    import json
    m = json.loads((a.manifest / "manifest.json").read_text())
    norm = m.get("norm_layers") or []
    if len(norm) != 1:
        sys.exit(f"st_gen_norm: expected one norm layer, found {len(norm)}")
    spec = norm[0]
    if spec["channels"] > MAX_CH:
        sys.exit(f"st_gen_norm: {spec['channels']} channels > {MAX_CH}")

    e_add, g, b = G.ln_consts(spec)
    if int(e_add) != LN_E_RTL:
        sys.exit(f"st_gen_norm: FAIL E = {int(e_add)} but st_norm has LN_E = {LN_E_RTL}")

    if int(np.max(np.abs(g))) > MUL_MAX:
        sys.exit(f"st_gen_norm: FAIL |G_c| = {int(np.max(np.abs(g)))} exceeds 2^17 - 1")
    if int(np.max(np.abs(b))) > OFF_MAX:
        sys.exit(f"st_gen_norm: FAIL |B_c| = {int(np.max(np.abs(b)))} exceeds 2^26 - 1")

    lut = np.asarray(G.LN_LUT, np.int64)
    lut_n = (1 << G.LN_L) - G.LN_M0
    if len(lut) != lut_n or int(lut.min()) < 0 or int(lut.max()) > LUT_MAX:
        sys.exit(f"st_gen_norm: FAIL LUT is not {lut_n} values in [0, 2^17)")

    a.out.mkdir(parents=True, exist_ok=True)
    for lane in range(LANES):
        path = a.out / f"st_ln_b{lane}.hex"
        with path.open("w") as fh:
            fh.write(f"// st_ln_b{lane}.hex -- LayerNorm coefficients of lane {lane},\n")
            fh.write(f"// {WORDS} x 48 bit, word a = channel {LANES}a + {lane}.\n")
            fh.write(f"// Generated by tools/st_gen_norm.py from {a.manifest.name}; "
                     "do not edit.\n")
            fh.write("// [44:18] B_c (27-bit signed), [17:0] G_c (18-bit signed);\n")
            fh.write("// words 20..255 are zero (st_norm's FiLM region is 128..147).\n")
            for a_i in range(WORDS):
                c = LANES * a_i + lane
                gg = int(g[c]) if c < len(g) else 0
                bb = int(b[c]) if c < len(b) else 0
                fh.write(f"{coeff_word(gg, bb):012x}\n")
    ln_path = a.out / "st_ln_b0.hex"

    lut_path = a.out / "st_ln_lut.hex"
    with lut_path.open("w") as fh:
        fh.write("// st_ln_lut.hex -- R = round(2^20 / sqrt(m + 0.5)), m = 256..1023.\n")
        fh.write(f"// Generated by tools/st_gen_norm.py from {a.manifest.name}; do not edit.\n")
        for v in lut:
            fh.write(f"{int(v):05x}\n")

    print(f"PASS st_gen_norm: st_ln_b0..b{LANES-1}.hex "
          f"({MAX_CH} channels, E = {LN_E_RTL}), "
          f"{lut_path} ({len(lut)} entries), "
          f"|G| <= {int(np.max(np.abs(g)))}, |B| <= {int(np.max(np.abs(b)))}, "
          f"R in [{int(lut.min())}, {int(lut.max())}]")
    return 0


if __name__ == "__main__":
    sys.exit(main())
