#!/usr/bin/env python3
"""Generate the board's live ST layer selector from an NNgen manifest.

The current on-chip board profile is intentionally a bounded 16x16 subset.  It
is a real manifest-to-RTL lowering step: layer order, tensor shape, operation
kind and weight offsets are read from the quantized export, then emitted as a
deterministic SystemVerilog selector and a JSON audit record.  The script
fails closed when the selected profile no longer fits the RTL's local limits.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


def resolve(root: Path, value: str) -> Path:
    p = Path(value)
    return p if p.is_absolute() else (root / p).resolve()


def emit(layers: list[dict]) -> str:
    lines = [
        "// Generated by tools/generate_st_board_config.py; do not edit.",
        "// Source: ink_dw W8A8 manifest; bounded 16x16 live board profile.",
        "module st_layer_sel (",
        "    input wire [3:0] idx,",
        "    output reg [7:0] ic, oc,",
        "    output reg [1:0] k, stride,",
        "    output reg pad, relu, out_unsigned, need_up, need_pool, is_dw,",
        "    output reg [16:0] w_off",
        ");",
        "    always @(*) begin",
        "        ic=8'd1; oc=8'd1; k=2'd3; stride=2'd1; pad=1'b1; relu=1'b1;",
        "        out_unsigned=1'b0; need_up=1'b0; need_pool=1'b0; is_dw=1'b0; w_off=17'd0;",
        "        case (idx)",
    ]
    for i, l in enumerate(layers):
        k = int(l["kernel"][0])
        s = int(l["stride"][0])
        groups = int(l["groups"])
        # The existing board RTL uses need_up as a virtual 2x input before
        # up3.1; preserve that board-specific lowering decision in the profile.
        need_up = 1 if l["name"] == "up3.1.dw" else 0
        lines.append(
            f"          4'd{i}: begin ic=8'd{l['in_channels']}; oc=8'd{l['out_channels']}; "
            f"k=2'd{k}; stride=2'd{s}; pad=1'b{int(bool(l['reflect_pad']))}; "
            f"relu=1'b{int(bool(l['out_relu']))}; out_unsigned=1'b{int(bool(l['out_unsigned']))}; "
            f"need_up=1'b{need_up}; need_pool=1'b0; is_dw=1'b{int(groups == int(l['in_channels']) and groups > 1)}; "
            f"w_off=17'd{l['weight_offset']}; end // {l['name']}"
        )
    lines += ["          default: ;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", type=Path, required=True)
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    ap.add_argument("--sv", type=Path, required=True)
    ap.add_argument("--weights-hex", type=Path, required=True)
    ap.add_argument("--report", type=Path, required=True)
    args = ap.parse_args()
    root = args.root.resolve()
    profile = json.loads(args.profile.read_text())
    manifest_path = resolve(root, profile["manifest"])
    manifest_bytes = manifest_path.read_bytes()
    manifest = json.loads(manifest_bytes)
    by_name = {l["name"]: l for l in manifest["layers"]}
    names = profile["layers"]
    missing = [n for n in names if n not in by_name]
    if missing:
        raise SystemExit("profile layer(s) missing from manifest: " + ", ".join(missing))
    layers = []
    packed_offset = 0
    for name in names:
        layer = dict(by_name[name])
        layer["source_weight_offset"] = int(layer["weight_offset"])
        layer["weight_offset"] = packed_offset
        packed_offset += int(layer["weight_bytes"])
        layers.append(layer)
    max_c = int(profile["max_channels"])
    max_spatial = int(profile["max_spatial"])
    cap = int(profile["weight_capacity_bytes"])
    used = packed_offset
    if used > cap:
        raise SystemExit(f"board profile weights {used} bytes exceed local capacity {cap}")
    for l in layers:
        if max(int(l["in_channels"]), int(l["out_channels"])) > max_c:
            raise SystemExit(f"{l['name']}: channels exceed profile max {max_c}")
    args.sv.parent.mkdir(parents=True, exist_ok=True)
    args.sv.write_text(emit(layers))
    weight_path = resolve(manifest_path.parent, manifest.get("weight_file", "weights.bin"))
    weight_bytes = weight_path.read_bytes()
    selected = bytearray()
    for layer in layers:
        start = int(layer["source_weight_offset"])
        size = int(layer["weight_bytes"])
        selected.extend(weight_bytes[start:start + size])
    if len(selected) != used:
        raise SystemExit(f"weight extraction produced {len(selected)} bytes, expected {used}")
    args.weights_hex.parent.mkdir(parents=True, exist_ok=True)
    args.weights_hex.write_text("".join(f"{b:02x}\n" for b in selected))

    def rel(p: Path) -> str:
        try:
            return str(p.resolve().relative_to(root))
        except ValueError:
            return str(p)

    report = {
        "format": "st-board-profile-v1",
        "profile": rel(args.profile),
        "manifest": rel(manifest_path),
        "manifest_sha256": hashlib.sha256(manifest_bytes).hexdigest(),
        "layers": names,
        "layer_count": len(layers),
        "weight_bytes": used,
        "weight_capacity_bytes": cap,
        "max_channels": max_c,
        "max_spatial": max_spatial,
        "rtl": rel(args.sv),
        "weights_hex": rel(args.weights_hex),
        "weights_source": rel(weight_path),
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
