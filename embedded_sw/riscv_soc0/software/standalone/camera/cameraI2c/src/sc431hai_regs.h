/* ============================================================================
 * sc431hai_regs.h  --  SC431HAI 上电初始化寄存器表 (157 条, 写序不可变)
 *
 * 1280x720 中心裁切 (不 binning), 4-lane RAW10.  当前基线.
 *
 * 基表是本板已验证的 1080p 裁切表 (edd33d9, 164 条): PLL / 模拟时序 / MIPI 原样保留,
 * 只改动:
 *   表首补 0x0103=0x01 软复位 (热写时清掉旧裁切窗口)
 *   不写 0x3200..0x3207 裁切窗口, 复位后为全阵列
 *   开流前写输出窗口 0x3208..0x320B = 1280x720, 起始 0x3210..0x3213 = (2, 2)
 *   开流后的 0x3E08/0x3E09 (模拟增益) 与 0x3221=0x66 (镜像+倒置) 沿用基表
 *
 * 2x2 binning 尚未调通 (板上实测, 2026-10-20):
 *   - 厂商 rockchip sc431hai.c 的 720p binning 表是 2-lane 的; 原样在本板 4-lane 下
 *     只收到 FS/FE 短包, 没有行数据.
 *   - 在本表基础上开流前追加厂商表独有的 binning 控制组
 *       0x3215=0x31  0x3220=0x01  0x5000=0x46  0x5900=0x01  0x5901=0x04
 *     能出 1280x720 且画面变亮, 但出现固定于输出坐标的块状错位与左侧异色竖条
 *     (镜像时场景翻转而纹路不动).  去掉这 5 条即正常, 所以问题在这组寄存器本身.
 *   - FPGA 读写通路已用逐帧变化的计数图样验证无断点、无旧帧残留.
 *
 * 数据手册 SC431HAI V1.1 1.4 节:
 *   - PAD SID 低 -> 7-bit 0x30 / 8-bit 写地址 0x60
 *   - 消息格式: 16-bit Sub Address(先高后低) + 8-bit data
 *   - 表内顺序即上电时序, 禁止重排
 * ==========================================================================*/
